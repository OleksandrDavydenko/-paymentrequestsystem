"""Довідник відділів компанії — до якого відділу належить співробітник.

Це НЕ поле «Відділ» зі статей витрат: статті, які бачить користувач, налаштовуються окремо
(«Статті бюджету»). Тут — оргструктура: відділ співробітника визначає, якому керівнику
відділу видно його заявки і хто їх погоджує.

Поки що — мокові дані. Пізніше список братиметься окремим запитом з Power BI
(той самий клієнт executeQueries, що в expense_items) — тоді get_departments()
читатиме його з кешем, а коди відділів у налаштуваннях і заявках лишаться ті самі.
"""

# код -> назва
MOCK_DEPARTMENTS = {
    "LOG": "Логістика",
    "CUS": "Митне оформлення",
    "ACC": "Бухгалтерія",
    "FIN": "Фінансовий відділ",
    "SAL": "Відділ продажу",
    "IT": "ІТ",
    "BA": "Відділ бізнес-аналізу",
    "ADM": "Адміністрація",
}


def get_departments():
    """[{"code", "name"}] за назвою."""
    return sorted(({"code": c, "name": n} for c, n in MOCK_DEPARTMENTS.items()), key=lambda d: d["name"].lower())


def get_map():
    return {d["code"]: d["name"] for d in get_departments()}


def get_name(code):
    """Назва відділу; код, якого вже немає в довіднику, — з позначкою."""
    if not code:
        return ""
    return get_map().get(code) or f"{code} (немає в довіднику)"


def status():
    return {"source": "mock", "count": len(get_departments())}
